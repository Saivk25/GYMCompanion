/// One signal's full detail. Reads from the same
/// [coachHomeControllerProvider] state Coach Home already holds — the
/// same "no second fetch for data already in memory" reasoning
/// `ReadinessEntryDetailScreen`/`MeasurementTrendScreen` already
/// established for their own modules.
///
/// There is deliberately little more to show here than the list row
/// already carries: a real backend `Recommendation` is exactly a
/// severity and a message (`app/domain/rules/recommendation.py`) —
/// nothing else exists to reveal. This screen's own value is
/// disclosure, not extra data: the full, untruncated message, and a
/// plain statement of which real rule engine produced it and when —
/// never a fabricated "why," a confidence percentage, or a rationale
/// beyond the message itself, none of which the backend's
/// `Recommendation` type carries (`docs/adr/0041-coach-module.md`).
class CoachSignalDetailScreen extends ConsumerWidget {
  const CoachSignalDetailScreen({required this.signalId, super.key});

  final String signalId;

  @override
  Widget build(BuildContext context, WidgetRef ref) {
    final AsyncValue<CoachHomeViewState> state = ref.watch(coachHomeControllerProvider);

    return Scaffold(
      appBar: AppBar(
        leading: IconButton(
          icon: const Icon(AppIcons.back),
          tooltip: 'Back',
          onPressed: () => Navigator.of(context).pop(),
        ),
        title: const Text('Guidance detail'),
      ),
      body: state.when(
        loading: () => const Center(child: AppLoadingIndicator()),
        error: (Object error, StackTrace stackTrace) => Center(
          child: AppErrorState(
            message: "This couldn't be loaded.",
            onRetry: () => ref.read(coachHomeControllerProvider.notifier).refresh(),
          ),
        ),
        data: (CoachHomeViewState data) {
          final Iterable<CoachSignal> matches =
              data.signals.where((CoachSignal s) => s.id == signalId);
          final CoachSignal? signal = matches.isEmpty ? null : matches.first;

          if (signal == null) {
            return const SafeArea(
              child: Center(
                child: AppEmptyState(
                  icon: AppIcons.coach,
                  title: 'Guidance not found',
                  message: 'It may have been part of an earlier session.',
                ),
              ),
            );
          }
          return _SignalDetail(signal: signal);
        },
      ),
    );
  }
}

class _SignalDetail extends StatelessWidget {
  const _SignalDetail({required this.signal});

  final CoachSignal signal;

  @override
  Widget build(BuildContext context) {
    final TextTheme textTheme = Theme.of(context).textTheme;
    final ColorScheme colorScheme = Theme.of(context).colorScheme;

    return SafeArea(
      child: ListView(
        padding: const EdgeInsets.all(AppSpacing.lg),
        children: <Widget>[
          Row(
            children: <Widget>[
              CoachSeverityBadge(severity: signal.severity),
              const SizedBox(width: AppSpacing.sm),
              Text(signal.module.label, style: textTheme.labelLarge),
            ],
          ),
          const SizedBox(height: AppSpacing.lg),
          Text(signal.message, style: textTheme.headlineSmall),
          const SizedBox(height: AppSpacing.xl),
          AppCard(
            child: Column(
              crossAxisAlignment: CrossAxisAlignment.start,
              mainAxisSize: MainAxisSize.min,
              children: <Widget>[
                Text('Where this came from', style: textTheme.titleMedium),
                const SizedBox(height: AppSpacing.sm),
                Text(
                  '${signal.module.label} guidance is generated by a real, '
                  "deterministic rule check on the backend — not a chat "
                  'assistant and not a prediction. It ran on '
                  '${_formattedDateTime(signal.occurredAt)}, in response to '
                  'an action you took this session.',
                  style: textTheme.bodyMedium?.copyWith(color: colorScheme.onSurfaceVariant),
                ),
              ],
            ),
          ),
        ],
      ),
    );
  }

  static String _formattedDateTime(DateTime dt) {
    const List<String> months = <String>[
      'January', 'February', 'March', 'April', 'May', 'June',
      'July', 'August', 'September', 'October', 'November', 'December',
    ];
    final int hour12 = dt.hour % 12 == 0 ? 12 : dt.hour % 12;
    final String minute = dt.minute.toString().padLeft(2, '0');
    final String period = dt.hour >= 12 ? 'PM' : 'AM';
    return '${months[dt.month - 1]} ${dt.day} at $hour12:$minute $period';
  }
}

"""The declarative base and naming convention shared by every ORM model.

A fixed naming convention makes autogenerated constraint/index names
deterministic across environments (`ix_users_...` rather than a
Postgres-assigned name that can differ run to run) — this is what lets
Alembic autogenerate produce stable, reviewable diffs instead of noisy
rename-everything migrations.

This module intentionally has zero framework-independence requirement
placed on it: it is `app/infra`, the layer that is *allowed* to know about
SQLAlchemy. `app/domain` (Sprint 1, Step 12) must never import from here.
"""

from sqlalchemy import MetaData
from sqlalchemy.orm import DeclarativeBase

# Standard, widely-used convention (this is the one recommended in
# SQLAlchemy's own documentation) so every constraint alembic generates has
# a predictable, greppable name.
NAMING_CONVENTION = {
    "ix": "ix_%(column_0_label)s",
    "uq": "uq_%(table_name)s_%(column_0_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    """Declarative base for every infra-layer ORM model."""

    metadata = MetaData(naming_convention=NAMING_CONVENTION)

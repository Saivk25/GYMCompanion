"""The Workout aggregate root.

The core consistency boundary for everything workout-related — planning,
execution, history. Domain Model & Decision Engine Bible, Section 4.7's
`WorkoutSession` is the closest analog, but this increment's `Workout` is a
deliberately simplified, standalone shape, not that aggregate rebuilt in
full. See `docs/adr/0006-workout-aggregate-first-increment.md` for the full
reasoning and what's deferred. Built entirely on the Sprint 1 shared kernel
(`app.domain.shared_kernel`), following the same pattern as
`app.domain.user.user.User`.
"""

from __future__ import annotations

from datetime import datetime

from app.domain.shared_kernel.aggregate_root import AggregateRoot
from app.domain.shared_kernel.clock import Clock
from app.domain.shared_kernel.validation import ensure
from app.domain.user.identifiers import UserId
from app.domain.workout.enums import WorkoutStatus
from app.domain.workout.events import (
    WorkoutCancelled,
    WorkoutCompleted,
    WorkoutPlanned,
    WorkoutStarted,
)
from app.domain.workout.identifiers import WorkoutId
from app.domain.workout.value_objects import (
    WorkoutDate,
    WorkoutDuration,
    WorkoutGoal,
    WorkoutName,
    WorkoutNotes,
)

# Every legal account-status-style transition, expressed as a table rather
# than a linear sequence — same technique and same reasoning as
# app/domain/user/user.py's _ALLOWED_TRANSITIONS. Both terminal states
# (Completed, Cancelled) map to an empty set: nothing may follow them,
# which is what makes "cannot start twice", "cannot complete twice", and
# "cannot cancel after completion" all true by construction rather than by
# a handful of separate, easy-to-miss guard clauses.
_ALLOWED_TRANSITIONS: dict[WorkoutStatus, frozenset[WorkoutStatus]] = {
    WorkoutStatus.PLANNED: frozenset({WorkoutStatus.IN_PROGRESS, WorkoutStatus.CANCELLED}),
    WorkoutStatus.IN_PROGRESS: frozenset({WorkoutStatus.COMPLETED, WorkoutStatus.CANCELLED}),
    WorkoutStatus.COMPLETED: frozenset(),
    WorkoutStatus.CANCELLED: frozenset(),
}


class Workout(AggregateRoot[WorkoutId]):
    """The Workout aggregate. See the module docstring for scope and the
    ADR for how this relates to the Bible's `WorkoutSession`.

    Construct a brand-new workout via the `plan()` factory, never
    `Workout(...)` directly — the constructor is also used to rehydrate an
    existing workout from a repository, where re-raising `WorkoutPlanned`
    would be wrong. See `plan()`, and `app.domain.user.user.User` for the
    same pattern explained in more depth.
    """

    def __init__(
        self,
        workout_id: WorkoutId,
        *,
        user_id: UserId,
        name: WorkoutName,
        planned_date: WorkoutDate,
        planned_at: datetime,
        status: WorkoutStatus = WorkoutStatus.PLANNED,
        goal: WorkoutGoal | None = None,
        notes: WorkoutNotes | None = None,
        duration: WorkoutDuration | None = None,
        started_at: datetime | None = None,
        completed_at: datetime | None = None,
        cancelled_at: datetime | None = None,
    ) -> None:
        super().__init__(workout_id)
        ensure(planned_at.tzinfo is not None, "planned_at must be timezone-aware")
        self._user_id = user_id
        self._name = name
        self._planned_date = planned_date
        self._planned_at = planned_at
        self._status = status
        self._goal = goal
        self._notes = notes
        self._duration = duration
        self._started_at = started_at
        self._completed_at = completed_at
        self._cancelled_at = cancelled_at

    @classmethod
    def plan(
        cls,
        *,
        workout_id: WorkoutId,
        user_id: UserId,
        name: WorkoutName,
        planned_date: WorkoutDate,
        goal: WorkoutGoal | None = None,
        notes: WorkoutNotes | None = None,
        clock: Clock,
    ) -> Workout:
        """Creates a brand-new Workout in the Planned state and records
        `WorkoutPlanned`. `workout_id` is generated by the caller
        (`WorkoutId.generate()`) before calling this — the same convention
        `User.register()` follows for `UserId`.
        """
        planned_at = clock.now()
        workout = cls(
            workout_id,
            user_id=user_id,
            name=name,
            planned_date=planned_date,
            planned_at=planned_at,
            goal=goal,
            notes=notes,
        )
        workout.record_event(
            WorkoutPlanned(
                occurred_at=planned_at,
                workout_id=workout_id,
                user_id=user_id,
                name=name,
                planned_date=planned_date,
            )
        )
        return workout

    @property
    def user_id(self) -> UserId:
        return self._user_id

    @property
    def name(self) -> WorkoutName:
        return self._name

    @property
    def planned_date(self) -> WorkoutDate:
        return self._planned_date

    @property
    def planned_at(self) -> datetime:
        return self._planned_at

    @property
    def status(self) -> WorkoutStatus:
        return self._status

    @property
    def goal(self) -> WorkoutGoal | None:
        return self._goal

    @property
    def notes(self) -> WorkoutNotes | None:
        return self._notes

    @property
    def duration(self) -> WorkoutDuration | None:
        return self._duration

    @property
    def started_at(self) -> datetime | None:
        return self._started_at

    @property
    def completed_at(self) -> datetime | None:
        return self._completed_at

    @property
    def cancelled_at(self) -> datetime | None:
        return self._cancelled_at

    def update_goal(self, goal: WorkoutGoal | None) -> None:
        """Replaces the workout's goal. No event: nothing in this
        increment's scope reads a goal edit independently of the aggregate
        itself — same reasoning as `User.update_preferences`."""
        self._ensure_mutable()
        self._goal = goal

    def update_notes(self, notes: WorkoutNotes | None) -> None:
        """Replaces the workout's notes. No event, same reasoning as
        `update_goal`. Blocked once Completed or Cancelled: the Bible's
        `WorkoutSession` is explicitly "immutable from this point" once
        Completed (Section 7.1, Table 30) — a real correction mechanism
        (an appended note rather than an overwrite) is deferred until a
        documented need for one shows up, per
        `docs/adr/0006-workout-aggregate-first-increment.md`."""
        self._ensure_mutable()
        self._notes = notes

    def start(self, *, clock: Clock) -> None:
        """Planned -> InProgress."""
        self._transition_to(WorkoutStatus.IN_PROGRESS)
        self._started_at = clock.now()
        self.record_event(
            WorkoutStarted(
                occurred_at=self._started_at,
                workout_id=self.id,
                user_id=self._user_id,
            )
        )

    def complete(self, *, duration: WorkoutDuration, clock: Clock) -> None:
        """InProgress -> Completed. `duration` is the user-relevant total
        logged time — see `WorkoutDuration`'s docstring for why it's a
        caller-supplied value, not derived from `started_at`."""
        self._transition_to(WorkoutStatus.COMPLETED)
        self._completed_at = clock.now()
        self._duration = duration
        self.record_event(
            WorkoutCompleted(
                occurred_at=self._completed_at,
                workout_id=self.id,
                user_id=self._user_id,
                duration=duration,
            )
        )

    def cancel(self, *, clock: Clock) -> None:
        """Planned -> Cancelled, or InProgress -> Cancelled."""
        self._transition_to(WorkoutStatus.CANCELLED)
        self._cancelled_at = clock.now()
        self.record_event(
            WorkoutCancelled(
                occurred_at=self._cancelled_at,
                workout_id=self.id,
                user_id=self._user_id,
            )
        )

    def _ensure_mutable(self) -> None:
        ensure(
            self._status not in (WorkoutStatus.COMPLETED, WorkoutStatus.CANCELLED),
            f"cannot modify a workout in status {self._status.value!r}",
        )

    def _transition_to(self, target: WorkoutStatus) -> None:
        allowed = _ALLOWED_TRANSITIONS[self._status]
        ensure(
            target in allowed,
            f"cannot transition workout status from {self._status.value!r} to {target.value!r}",
        )
        self._status = target

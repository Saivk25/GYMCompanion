"""The User aggregate root.

Root identity anchor for one human using Gym Companion — every other
aggregate is eventually owned by exactly one User (Domain Model & Decision
Engine Bible, Section 4.1, Table 4, "Purpose"). This is Sprint 2's first
real aggregate, built entirely on the Sprint 1 shared kernel
(`app.domain.shared_kernel`).
"""

from __future__ import annotations

from datetime import datetime

from app.domain.shared_kernel.aggregate_root import AggregateRoot
from app.domain.shared_kernel.clock import Clock
from app.domain.shared_kernel.validation import ensure
from app.domain.user.enums import AccountStatus
from app.domain.user.events import UserProfileUpdated, UserRegistered
from app.domain.user.identifiers import UserId
from app.domain.user.value_objects import AuthMethod, Locale, Timezone, UserPreferences, UserProfile

# The Bible's documented lifecycle (Section 4.1, Table 4): "Invited -> Active
# -> Suspended (optional) -> Deleted (soft) -> Purged (hard)", plus its one
# named exception to "one-directional": "Suspended -> Active". Read as a
# transition table rather than a linear sequence because the real rule is
# richer than the arrow diagram suggests once "the user has full ... delete
# rights over everything it owns" (same table, "Ownership") is taken
# seriously: deletion must be reachable from every non-terminal state, not
# only from the end of the happy path.
_ALLOWED_TRANSITIONS: dict[AccountStatus, frozenset[AccountStatus]] = {
    AccountStatus.INVITED: frozenset({AccountStatus.ACTIVE, AccountStatus.DELETED}),
    AccountStatus.ACTIVE: frozenset({AccountStatus.SUSPENDED, AccountStatus.DELETED}),
    AccountStatus.SUSPENDED: frozenset({AccountStatus.ACTIVE, AccountStatus.DELETED}),
    AccountStatus.DELETED: frozenset({AccountStatus.PURGED}),
    AccountStatus.PURGED: frozenset(),
}


class User(AggregateRoot[UserId]):
    """The User / Account aggregate. See the module docstring and Bible
    Section 4.1, Table 4 for the full purpose/responsibilities/rules.

    Construct a brand-new user via the `register()` factory, never
    `User(...)` directly — the constructor is also used to rehydrate an
    existing user from a repository, where re-raising `UserRegistered`
    would be wrong. See `register()`.
    """

    def __init__(
        self,
        user_id: UserId,
        *,
        created_at: datetime,
        locale: Locale,
        timezone: Timezone,
        auth_method: AuthMethod,
        account_status: AccountStatus = AccountStatus.INVITED,
        profile: UserProfile | None = None,
        preferences: UserPreferences | None = None,
    ) -> None:
        super().__init__(user_id)
        ensure(created_at.tzinfo is not None, "created_at must be timezone-aware")
        self._created_at = created_at
        self._locale = locale
        self._timezone = timezone
        self._auth_method = auth_method
        self._account_status = account_status
        self._profile = profile
        self._preferences = preferences if preferences is not None else UserPreferences()

    @classmethod
    def register(
        cls,
        *,
        user_id: UserId,
        locale: Locale,
        timezone: Timezone,
        auth_method: AuthMethod,
        clock: Clock,
    ) -> User:
        """Creates a brand-new User in the Invited state and records
        `UserRegistered`. `user_id` is generated by the caller
        (`UserId.generate()`) before calling this — matching the existing
        convention on `UserAccount` in `app/infra/models.py`, where the id
        is always minted in application code before the row is persisted.
        """
        registered_at = clock.now()
        user = cls(
            user_id,
            created_at=registered_at,
            locale=locale,
            timezone=timezone,
            auth_method=auth_method,
        )
        user.record_event(
            UserRegistered(
                occurred_at=registered_at,
                user_id=user_id,
                locale=locale,
                timezone=timezone,
            )
        )
        return user

    @property
    def created_at(self) -> datetime:
        return self._created_at

    @property
    def locale(self) -> Locale:
        return self._locale

    @property
    def timezone(self) -> Timezone:
        return self._timezone

    @property
    def auth_method(self) -> AuthMethod:
        return self._auth_method

    @property
    def account_status(self) -> AccountStatus:
        return self._account_status

    @property
    def profile(self) -> UserProfile | None:
        return self._profile

    @property
    def preferences(self) -> UserPreferences:
        return self._preferences

    @property
    def has_complete_profile(self) -> bool:
        """`UserProfile` is always fully valid or absent (see its
        docstring) — completeness is exactly "has a profile been set",
        mapping the Bible's Profile Draft/Complete lifecycle states onto
        `profile is not None` without a separate state machine.
        """
        return self._profile is not None

    def update_profile(self, profile: UserProfile, *, clock: Clock) -> None:
        """Replaces the user's profile and records `UserProfileUpdated`."""
        self._ensure_mutable()
        self._profile = profile
        self.record_event(
            UserProfileUpdated(occurred_at=clock.now(), user_id=self.id, profile=profile)
        )

    def update_preferences(self, preferences: UserPreferences) -> None:
        """Replaces the user's preferences. No event is raised: nothing in
        this increment's scope reads preference changes outside the
        aggregate itself. Add `UserPreferencesUpdated` when a real
        consumer (e.g. Notification & Automation reacting to a quiet-hours
        change) needs one — see `events.py`'s module docstring.
        """
        self._ensure_mutable()
        self._preferences = preferences

    def activate(self) -> None:
        """Invited -> Active, or Suspended -> Active.

        One method for both source states, not two ("activate" and
        "reactivate"): the Bible names only a state graph (Section 4.1,
        Table 4, "Lifecycle / states" plus its one documented exception to
        "one-directional", Suspended -> Active), never two distinct
        verbs for reaching Active. A separate `reactivate()` that happened
        to share `_transition_to`'s table with `activate()` was tried
        during development and rejected: both would target the same
        `AccountStatus.ACTIVE`, so the shared table could not actually
        distinguish "reactivating from Suspended" from "activating from
        Invited" — a caller could reach Active from either state through
        either method name, silently defeating the two-method split's own
        purpose. Caught by the test asserting `reactivate()` must fail from
        Invited, which it didn't. One method, legal from both documented
        source states, has no such gap.
        """
        self._transition_to(AccountStatus.ACTIVE)

    def suspend(self) -> None:
        """Active -> Suspended."""
        self._transition_to(AccountStatus.SUSPENDED)

    def delete(
        self,
        *,
        has_unresolved_escalation: bool = False,
        escalation_acknowledged: bool = False,
    ) -> None:
        """Soft-deletes the account (-> Deleted).

        Enforces the Bible's business rule (Section 4.1, Table 4): "A User
        cannot be deleted while an unresolved EscalationCase is open
        without an explicit acknowledgement step." `EscalationCase` (Recovery
        & Safety bounded context) doesn't exist yet in this codebase, and a
        single aggregate transaction may not reach across to query another
        aggregate directly (Bible Section 3, "Aggregate consistency
        boundary") — so the caller (a future application service that *can*
        legitimately read both aggregates) supplies the two facts this rule
        actually needs, rather than `User` reaching outside its own
        boundary to look them up itself.
        """
        ensure(
            not has_unresolved_escalation or escalation_acknowledged,
            "cannot delete a user while an unresolved EscalationCase is open "
            "without an explicit acknowledgement",
        )
        self._transition_to(AccountStatus.DELETED)

    def purge(self) -> None:
        """Hard-deletes the account (-> Purged). Per the Bible, this
        cascades to every aggregate the User owns (Section 9's
        `AccountPurged` event) — orchestrating that cascade is an
        application-layer concern once those aggregates exist, not
        something this method can do from inside the User aggregate alone.
        """
        self._transition_to(AccountStatus.PURGED)

    def _ensure_mutable(self) -> None:
        ensure(
            self._account_status not in (AccountStatus.DELETED, AccountStatus.PURGED),
            f"cannot modify a user in account_status {self._account_status.value!r}",
        )

    def _transition_to(self, target: AccountStatus) -> None:
        allowed = _ALLOWED_TRANSITIONS[self._account_status]
        ensure(
            target in allowed,
            f"cannot transition user account_status from "
            f"{self._account_status.value!r} to {target.value!r}",
        )
        self._account_status = target

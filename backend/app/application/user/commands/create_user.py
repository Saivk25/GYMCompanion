"""`CreateUserCommand`: the input to `CreateUserHandler`.

Carries exactly the fields `User.register(...)` needs from a caller —
`locale`, `timezone`, `auth_method` — as the same domain value objects
the aggregate itself takes, not primitives. This phase builds no
serialization boundary (no FastAPI request model) that would need
primitive fields; a future API layer is where "parse a JSON body into
these value objects" belongs, not here. `user_id` is deliberately
absent: `User.register(...)`'s own docstring is explicit that the id
is "generated by the caller... before calling this," and here that
caller is `CreateUserHandler` itself, not whoever issues the command —
see `create_user_handler.py`.
"""

from __future__ import annotations

from dataclasses import dataclass

from app.application.shared.command import Command
from app.domain.user.value_objects import AuthMethod, Locale, Timezone


@dataclass(frozen=True, kw_only=True)
class CreateUserCommand(Command):
    """Register a brand-new User."""

    locale: Locale
    timezone: Timezone
    auth_method: AuthMethod

"""`CreateGoalCommand`: the input to `CreateGoalHandler`.

Carries exactly what `Goal.create(...)` needs — `user_id`, `goal_type`,
`name`, `target_date`, and the optional `description`/`target_weight`/
`target_body_fat`/`target_strength`/`priority`/`notes` — as the same
domain value objects the aggregate itself takes, matching
`app.application.workout.commands.create_workout.CreateWorkoutCommand`'s
own reasoning: no serialization boundary exists yet that would need
primitive fields. `goal_id` is absent for the identical reason
`workout_id` is absent from `CreateWorkoutCommand` — minted by
`CreateGoalHandler` itself, matching `Goal.create(...)`'s own documented
"generated by the caller" convention.
"""

from __future__ import annotations

from dataclasses import dataclass

from app.application.shared.command import Command
from app.domain.goal.enums import GoalType
from app.domain.goal.value_objects import (
    GoalDescription,
    GoalName,
    GoalNotes,
    Priority,
    TargetBodyFat,
    TargetDate,
    TargetStrength,
    TargetWeight,
)
from app.domain.user.identifiers import UserId


@dataclass(frozen=True, kw_only=True)
class CreateGoalCommand(Command):
    """Create a brand-new, Active Goal for an existing User."""

    user_id: UserId
    goal_type: GoalType
    name: GoalName
    target_date: TargetDate
    description: GoalDescription | None = None
    target_weight: TargetWeight | None = None
    target_body_fat: TargetBodyFat | None = None
    target_strength: TargetStrength | None = None
    priority: Priority | None = None
    notes: GoalNotes | None = None

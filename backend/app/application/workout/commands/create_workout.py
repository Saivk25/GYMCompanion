"""`CreateWorkoutCommand`: the input to `CreateWorkoutHandler`.

Carries exactly what `Workout.plan(...)` needs — `user_id`, `name`,
`planned_date`, and the optional `goal`/`notes` — as the same domain
value objects the aggregate itself takes, matching
`app.application.user.commands.create_user.CreateUserCommand`'s own
reasoning: no serialization boundary exists yet that would need
primitive fields. `workout_id` is absent for the identical reason
`user_id` is absent from `CreateUserCommand` — minted by
`CreateWorkoutHandler` itself, matching `Workout.plan(...)`'s own
documented "generated by the caller" convention.
"""

from __future__ import annotations

from dataclasses import dataclass

from app.application.shared.command import Command
from app.domain.user.identifiers import UserId
from app.domain.workout.value_objects import WorkoutDate, WorkoutGoal, WorkoutName, WorkoutNotes


@dataclass(frozen=True, kw_only=True)
class CreateWorkoutCommand(Command):
    """Plan a brand-new Workout for an existing User."""

    user_id: UserId
    name: WorkoutName
    planned_date: WorkoutDate
    goal: WorkoutGoal | None = None
    notes: WorkoutNotes | None = None
